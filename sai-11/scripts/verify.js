const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'../public');
const js=fs.readFileSync(path.join(base,'app.js'),'utf8');
const css=fs.readFileSync(path.join(base,'styles.css'),'utf8');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const assert=(c,m)=>{if(!c)throw Error('SAI v11: '+m)};
const assets=fs.readdirSync(path.join(base,'assets'));
const referenced=[...new Set([...js.matchAll(/'([A-Za-z0-9_-]+\.(?:png|webp|svg))'/g)].map(m=>m[1]))];
for(const file of referenced) assert(assets.includes(file),'Missing referenced image: '+file);
for(const file of ['hero-logo.png','hero-symbol-mobile.png','favicon.png','holder-main-hq.webp','isao-mori-full.webp','isao-mori-full-640.webp','sticks-approved.webp','matches-approved.webp']) assert(assets.includes(file),'Missing required asset: '+file);
for(const id of ['holder','rice','matches','zine','vinyl']) assert(js.includes("id:'"+id+"'"),'Missing product '+id);
assert((js.match(/id:'(?:holder|rice|matches|zine|vinyl)'/g)||[]).length===5,'Expected exactly five entries');
assert(js.includes('id="intro-enter"'),'Intro not found');
assert(js.includes('product-card-feature')&&css.includes('grid-template-rows:180px 156px 156px'),'Collection grid mutated');
assert(js.includes('isao-mori-full.webp')&&js.includes('srcset='),'Optimized portrait not used');
assert(!js.includes('image-gallery')&&!js.includes('data-photo'),'Unwanted holder gallery');
assert(js.includes('CONNECT')&&js.includes('@sai.incense')&&js.includes('sai.scents@info.com'),'Contacts missing');
assert(js.includes('The face of SAI.')&&js.includes('Form reduced.'),'Philosophy blocks missing');
assert(js.includes('warmProductMedia')&&html.includes('isao-mori-full.webp'),'Prefetch missing');
assert(css.includes('sai-mist')&&css.includes('route-initial.route-visible'),'Smooth fade missing');
assert(css.includes('--glow-x')&&js.includes("setProperty('--glow-x'"),'Metallic cursor highlight missing');
assert(css.includes('.connect-block a:hover')&&css.includes('border-bottom-color:transparent'),'Contact hover regression');
assert(html.includes('href="/" data-view="intro" class="brand-link"'),'Brand home navigation missing');
console.log('SAI v11 static QA OK ('+referenced.length+' referenced assets)');
