const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'../public');
const js=fs.readFileSync(path.join(base,'app.js'),'utf8');
const css=fs.readFileSync(path.join(base,'styles.css'),'utf8');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const assert=(condition,message)=>{if(!condition)throw Error('SAI v8: '+message)};
const declared=[...new Set([...js.matchAll(/'([A-Za-z0-9_-]+\.(?:png|webp|svg))'/g)].map(match=>match[1]))];
for(const f of declared)assert(fs.existsSync(path.join(base,'assets',f)),'Missing asset: '+f);
for(const f of ['hero-logo.png','favicon.png','holder-main-hq.png','holder-angle-02.png','holder-angle-03.png','isao-mori-portrait-approved.png']) assert(fs.existsSync(path.join(base,'assets',f)),'Required asset missing: '+f);
assert(js.includes('id="intro-enter"'),'Approved first screen missing');
assert(js.includes('image-gallery'),'Holder gallery missing');
assert(js.includes("['holder-main-hq.png','Full view']"),'Original Holder front view replaced');
assert(js.includes("['holder-angle-02.png','Overhead view']"),'Second Holder view not user supplied');
assert(js.includes("['holder-angle-03.png','Reverse angle']"),'Third Holder view not user supplied');
assert(js.includes("asset('isao-mori-portrait-approved.png')"),'Approved portrait missing');
for(const id of ['holder','rice','matches','zine','vinyl'])assert(js.includes("id:'"+id+"'"),'Missing item '+id);
assert((js.match(/id:'(?:holder|rice|matches|zine|vinyl)'/g)||[]).length===5,'Unexpected product count');
assert(!js.includes("id:'hinoki'") && !js.includes("id:'tea'"),'Old scents still in catalog');
assert(js.includes('product-card-feature') && css.includes('.product-card-feature'),'Featured Holder panel missing');
assert(css.includes('grid-template-columns:repeat(2,minmax(0,1fr))'),'Two-column collection missing');
assert(css.includes('background:linear-gradient(105deg'),'Subtle hover effect missing');
assert(css.includes('.page.route-exit'),'Page transition broken');
assert(css.includes('overflow-y:auto'),'Page scrolling broken');
assert(!js.includes('philosophy-card quote'),'Unwanted quote returned');
assert(html.includes('favicon.png'),'Favicon missing');
assert(html.includes('/assets/holder-main-hq.png'),'Bad preload on main Holder image');
console.log('SAI v8 static QA OK; '+declared.length+' referenced images exist.');
